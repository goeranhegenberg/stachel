// Copies the constants of the Stachel web app (`stachel/docs/native_fixtures/web/constants.json`, generated from the web
// code by `stachel/tools/native-web-constants.mts`, contract §8.13) into `lib/src/web/web_constants.g.dart` and the test
// fixture `docs/native_fixtures/web/constants.json` – the app reads palettes, sizes, catalogs and texts from there instead of
// copying values by hand (parity audit §3.3).
//
//   dart run tool/gen_web_constants.dart [path to the stachel repo]   (default ../../.., the repo root)
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final repo = args.isEmpty ? '../../..' : args.first;
  final json = File('$repo/docs/native_fixtures/web/constants.json').readAsStringSync().replaceAll('\r\n', '\n').trim();
  jsonDecode(json); // valid?
  if (json.contains("'''")) throw StateError('unexpected triple quote in the constants');
  final out = File('lib/src/web/web_constants.g.dart');
  out.writeAsStringSync(
    '// GENERATED by tool/gen_web_constants.dart from stachel/docs/native_fixtures/web/constants.json – do not edit.\n'
    '// ignore_for_file: lines_longer_than_80_chars\n\n'
    '/// Constants of the web app (colors, font sizes, shapes, stickers, templates, card status, timeline, mind map,\n'
    '/// reactions, timer, frames) as JSON – read through `WebConstants`.\n'
    "const webConstantsJson = r'''$json''';\n",
  );
  stdout.writeln('written: ${out.path} (${(out.lengthSync() / 1024).round()} KB)');
}
