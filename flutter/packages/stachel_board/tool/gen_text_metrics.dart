// Copies the text metrics of the Stachel server (`stachel/server/src/native/text-metrics.json`, measured in Chromium
// with the web app's fonts by `stachel/tools/text-metrics.mts`) into `lib/src/mindmap/text_metrics.g.dart`, so the
// app sizes mind map nodes exactly like the server and the browser.
//
//   dart run tool/gen_text_metrics.dart [path to the stachel repo]   (default ../../.., the repo root)
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final repo = args.isEmpty ? '../../..' : args.first;
  final src = File('$repo/server/src/native/text-metrics.json');
  final json = src.readAsStringSync().trim();
  jsonDecode(json); // valid?
  if (json.contains("'''")) throw StateError('unexpected triple quote in the metrics');
  final out = File('lib/src/mindmap/text_metrics.g.dart');
  out.writeAsStringSync(
    '// GENERATED by tool/gen_text_metrics.dart from stachel/server/src/native/text-metrics.json – do not edit.\n'
    '// ignore_for_file: lines_longer_than_80_chars\n\n'
    '/// Text metrics of all fonts the web app measures (Barlow, Barlow Condensed, Source Serif 4, JetBrains Mono,\n'
    '/// 400–900, normal and italic: widths, kerning pairs, ligature triples per 1000 px, aliases – contract §8.13).\n'
    "const textMetricsJson = r'''$json''';\n",
  );
  stdout.writeln('written: ${out.path} (${(out.lengthSync() / 1024).round()} KB)');
}
