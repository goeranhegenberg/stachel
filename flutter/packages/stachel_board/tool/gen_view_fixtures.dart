// Copies the view reference values of the Stachel web app (`stachel/docs/native_fixtures/web/view.json`, generated from
// the web code by `stachel/tools/native-view-fixtures.mts`, parity audit P4) into the test fixture
// `docs/native_fixtures/web/view.json` and writes the search folding table `lib/src/features/search/fold_table.g.dart` (every
// character whose web folding – NFD without marks, lower case, ß → ss – differs from `toLowerCase`).
//
//   dart run tool/gen_view_fixtures.dart [path to the stachel repo]   (default ../../.., the repo root)
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final repo = args.isEmpty ? '../../..' : args.first;
  final json = File('$repo/docs/native_fixtures/web/view.json').readAsStringSync().replaceAll('\r\n', '\n').trim();
  final data = jsonDecode(json) as Map<String, Object?>;
  final fold = (data['fold'] as Map).cast<String, String>();
  final keys = fold.keys.map((k) => k.codeUnitAt(0)).toList()..sort();
  String lit(String s) => "'${s.codeUnits.map((c) => r'\u{' '${c.toRadixString(16)}}').join()}'";
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_view_fixtures.dart from stachel/docs/native_fixtures/web/view.json – do not edit.')
    ..writeln()
    ..writeln('/// Web search folding per character (`ui/search.ts` `fold`: NFD without combining marks, lower case, ß → ss)')
    ..writeln('/// where it differs from `toLowerCase` – Hangul syllables are decomposed by formula in `search_model.dart`.')
    ..writeln('const foldTable = <int, String>{');
  for (final k in keys) {
    b.writeln('  0x${k.toRadixString(16)}: ${lit(fold[String.fromCharCode(k)]!)},');
  }
  b.writeln('};');
  final out = File('lib/src/features/search/fold_table.g.dart')..writeAsStringSync(b.toString());
  stdout.writeln('written: ${out.path} (${keys.length} characters)');
}
