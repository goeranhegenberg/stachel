// Copies the objects of the web's template gallery (`stachel/docs/native_fixtures/web/templates.json`, generated from the
// web code by `stachel/tools/native-template-fixtures.mts`) into `lib/src/features/templates/template_previews.g.dart`
// – the app draws the gallery previews from them with its own painter (parity audit I29, package P3) – and the reference
// values `structure.json` into the package tests. Inserting always
// goes through the server's web action `structure.template` (built fresh there).
//
//   dart run tool/gen_template_previews.dart [path to the stachel repo]   (default ../../.., the repo root)
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final repo = args.isEmpty ? '../../..' : args.first;
  final json = File('$repo/docs/native_fixtures/web/templates.json').readAsStringSync().replaceAll('\r\n', '\n').trim();
  jsonDecode(json); // valid?
  if (json.contains("'''")) throw StateError('unexpected triple quote in the templates');
  final out = File('lib/src/features/templates/template_previews.g.dart');
  out.writeAsStringSync(
    '// GENERATED by tool/gen_template_previews.dart from stachel/docs/native_fixtures/web/templates.json – do not edit.\n'
    '// ignore_for_file: lines_longer_than_80_chars\n\n'
    '/// Objects of every template of the web gallery (fixed IDs, dates relative to 2026-01-05) for the previews.\n'
    "const templatePreviewsJson = r'''$json''';\n",
  );
  stdout.writeln('written: ${out.path} (${(out.lengthSync() / 1024).round()} KB)');
  // reference values of the web code (card height, tables, „Einfügen als …“) for the package tests
  final ref = File('$repo/docs/native_fixtures/web/structure.json').readAsStringSync().replaceAll('\r\n', '\n');
  jsonDecode(ref);
  File('test/features/cards/structure_reference.json')
    ..createSync(recursive: true)
    ..writeAsStringSync(ref);
  stdout.writeln('written: test/features/cards/structure_reference.json');
}
